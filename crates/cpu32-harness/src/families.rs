/// The instruction `opcode` encodes, by the CPU32's opcode map; "?" for
/// an opcode no pattern matches.
#[must_use]
pub fn family(opcode: u16) -> &'static str {
    FAMILIES
        .iter()
        .find(|&&(mask, pattern, _)| opcode & mask == pattern)
        .map_or("?", |&(_, _, name)| name)
}

