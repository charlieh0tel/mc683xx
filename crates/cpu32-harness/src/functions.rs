/// The generated cases a function runs (`harness.py`'s `PLAIN_CASES`).
pub const CASES: usize = 6;
/// Arguments the cases cycle through, by kind (`harness.py`).
const INTEGERS: [i64; CASES] = [0, 1, -1, 0x1234_5678, -100_000, 7];
const CHARS: [i8; CASES] = [-1, 0x41, 0x7f, 0, -0x80, 3];
const SHORTS: [i16; CASES] = [-2, 0x1234, -30000, 0, 0x7fff, 9];
const REALS: [f64; CASES] = [1.5, -2.25, 1e10, 3.0e-5, 0.0, 123.456];
/// What a `char *` points at.
const TEXT: &[u8] = b"123.456\0";
/// What both copies find on the stack where no declared argument lies
/// (`function_check.py`'s `UNDECLARED`).
const UNDECLARED: &[u8] = b"101010101010";
/// The first stack argument's offset from SP at entry.
const FIRST_ARGUMENT: usize = 4;
/// The alignment the 68k keeps the stack at.
const STACK_ALIGNMENT: usize = 2;
/// The widest argument or result the harness lays out.
const WIDEST: usize = 8;
/// A register's value before a call, distinct for each register
/// (`harness.py`'s `SENTINEL`).
const SENTINEL: u32 = 0x5a5a_0000;
/// The registers a C callee keeps (`harness.py`'s `CALLEE_SAVED`).
const CALLEE_SAVED: [&str; 11] = [
    "D2", "D3", "D4", "D5", "D6", "D7", "A2", "A3", "A4", "A5", "A6",
];
/// Every register a routine may take, by the sidecar's name, in
/// `harness.py`'s order.
const REGISTERS: [&str; 15] = [
    "D0", "D1", "D2", "D3", "D4", "D5", "D6", "D7", "A0", "A1", "A2", "A3", "A4", "A5", "A6",
];
/// The A6 register's index in `REGISTERS`.
const A6: usize = 14;
/// The conventions whose callees keep `CALLEE_SAVED`.
const C_CONVENTIONS: [&str; 2] = ["c", "unknown"];
/// A sidecar `preserves` entry meaning every register.
const PRESERVES_ALL: &str = "all";
/// The sidecar's separator between an overlay's name and an address.
const OVERLAY_SEPARATOR: &str = "::";
/// The SR bits a call leaves its caller as it found them.
const SYSTEM_BYTE: u16 = 0xff00;
/// The functions that set SR's interrupt mask to their first argument's
/// bits 10 to 8, keeping the rest of SR (smartclock
/// `docs/firmware/quirks.md`, `set_interrupt_mask`): the one change to
/// the system byte a call makes for its caller.
const MASK_SETTERS: [&str; 1] = ["set_interrupt_mask"];
/// The kernel's I/O functions, which return their error in D7 for
/// `kernel_dispatch_io` to hand the trap's caller (smartclock
/// `docs/firmware/quirks.md`, `duartb_reconfigure`): D7 is theirs to
/// change.
const IO_FUNCTIONS: [&str; 2] = ["duartb_reconfigure", "sci_reconfigure"];
/// D7's index in `REGISTERS`.
const D7: usize = 7;
/// The exceptions that are the CPU32's answer to a function on its
/// generated arguments, not the core's fault: the function, the
/// vector, and why.
const EXPLAINED: &[(&str, Vector, &str)] = &[(
    "longjmp",
    Vector::TRACE,
    "trap #1 restores SR from the jmp_buf, generated bytes with T1 set",
)];
/// The sizes of the base types the decompiled C's prototypes use
/// (`harness.py`'s `BASE_SIZES`).
const BASE_SIZES: &[(&str, usize)] = &[
    ("char", 1),
    ("byte", 1),
    ("uchar", 1),
    ("undefined1", 1),
    ("uint8_t", 1),
    ("int8_t", 1),
    ("bool", 1),
    ("short", 2),
    ("ushort", 2),
    ("undefined2", 2),
    ("uint16_t", 2),
    ("int16_t", 2),
    ("int", 4),
    ("uint", 4),
    ("long", 4),
    ("ulong", 4),
    ("undefined4", 4),
    ("uint32_t", 4),
    ("int32_t", 4),
    ("float", 4),
    ("double", 8),
    ("undefined8", 8),
    ("longlong", 8),
    ("ulonglong", 8),
    ("uint64_t", 8),
    ("int64_t", 8),
];
/// Each image's caller's name, which a call's caller's frame holds
/// (`harness.py`'s profiles, `caller_name`), by the image's name.
pub const IMAGES: &[(&str, u32)] = &[("z3805a-3543b", 0x131f7), ("58503a-3704", 0x1340a)];

/// What is wrong with an image's sidecar or C.
#[derive(Debug, thiserror::Error)]
pub enum CorpusError {
    /// A line of the sidecar is not JSON.
    #[error("sidecar line {line}: {error}")]
    Json {
        /// Its number, from 1.
        line: usize,
        /// Why.
        error: serde_json::Error,
    },
    /// A sidecar row lacks a field or has it of the wrong type.
    #[error("sidecar line {line}: no {field}")]
    Field {
        /// Its number, from 1.
        line: usize,
        /// The field.
        field: &'static str,
    },
}

/// The C's types: which name pointers, their sizes, and the routine
/// types (`harness.py`'s `Types`).
#[derive(Debug, Default)]
struct Types {
    /// The typedefs that name pointers.
    pointers: BTreeSet<String>,
    /// Sizes, by type name.
    sizes: BTreeMap<String, usize>,
    /// The routine typedefs.
    routines: BTreeSet<String>,
}

impl Types {
    fn new(c: &str) -> Self {
        let pointer = Regex::new(r"(?m)^typedef [^;()]*\*\s*(\w+);$").expect("a regex");
        let size = Regex::new(r"(?m)^_Static_assert\(sizeof\((\w+)\) == (\d+),").expect("a regex");
        let routine =
            Regex::new(r"(?m)^typedef ([^;()]+?) ?\((\w+)\)\(([^()]+)\);$").expect("a regex");
        let mut sizes: BTreeMap<String, usize> = BASE_SIZES
            .iter()
            .map(|&(name, size)| (name.to_owned(), size))
            .collect();
        for captures in size.captures_iter(c) {
            sizes.insert(captures[1].to_owned(), captures[2].parse().expect("digits"));
        }
        Self {
            pointers: pointer
                .captures_iter(c)
                .map(|captures| captures[1].to_owned())
                .collect(),
            sizes,
            routines: routine
                .captures_iter(c)
                .map(|captures| captures[2].to_owned())
                .collect(),
        }
    }

    fn is_pointer(&self, kind: &str) -> bool {
        kind.ends_with('*') || self.pointers.contains(kind)
    }

    /// Whether `kind` points at a routine type.
    fn is_routine(&self, kind: &str) -> bool {
        kind.strip_suffix('*')
            .is_some_and(|pointee| self.routines.contains(pointee.trim()))
    }

    fn size(&self, kind: &str) -> Option<usize> {
        if self.is_pointer(kind) {
            Some(4)
        } else {
            self.sizes.get(kind).copied()
        }
    }
}

/// A function the corpus calls.
#[derive(Debug, Clone)]
pub struct Function {
    /// Its name.
    pub name: String,
    /// Its entry.
    pub address: u32,
    /// Its parameters' types.
    kinds: Vec<String>,
    /// Where the image's copy reads each, from SP at entry.
    offsets: Vec<usize>,
    /// The registers it keeps for its caller, as indexes of
    /// `REGISTERS`.
    preserves: Vec<usize>,
}

/// An image's functions: those the corpus calls, and how many of the
/// C's it cannot lay out a call to.
#[derive(Debug)]
pub struct Corpus {
    /// The functions, in the C's order.
    pub functions: Vec<Function>,
    /// The functions not run: no known size, a structure or variable
    /// list, an overlay's, or a stack that does not match.
    pub unrunnable: usize,
    /// The C's types.
    types: Types,
}

/// The registers a convention keeps (`harness.py`'s
/// `preserved_registers`).
fn preserved(convention: &Value) -> Vec<usize> {
    let listed: BTreeSet<&str> = convention["preserves"]
        .as_array()
        .map(|names| names.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    let c = convention["convention"]
        .as_str()
        .is_some_and(|name| C_CONVENTIONS.contains(&name));
    let returns_in_d7 = convention["name"]
        .as_str()
        .is_some_and(|name| IO_FUNCTIONS.contains(&name));
    REGISTERS
        .iter()
        .enumerate()
        .filter(|&(_, name)| {
            listed.contains(PRESERVES_ALL)
                || listed.contains(name)
                || c && CALLEE_SAVED.contains(name)
        })
        .map(|(index, _)| index)
        .filter(|&index| !(returns_in_d7 && index == D7))
        .collect()
}

impl Corpus {
    /// The functions of an image from its decompiled C and sidecar, as
    /// `function_check.py`'s `functions` finds them, the primary's
    /// alone.
    pub fn new(c: &str, sidecar: &str) -> Result<Self, CorpusError> {
        let types = Types::new(c);
        let mut conventions: BTreeMap<String, Value> = BTreeMap::new();
        for (index, line) in sidecar
            .lines()
            .enumerate()
            .filter(|(_, line)| !line.is_empty())
        {
            let line_number = index + 1;
            let row: Value = serde_json::from_str(line).map_err(|error| CorpusError::Json {
                line: line_number,
                error,
            })?;
            let name = row["name"].as_str().ok_or(CorpusError::Field {
                line: line_number,
                field: "name",
            })?;
            if row["address"].as_str().is_none() {
                return Err(CorpusError::Field {
                    line: line_number,
                    field: "address",
                });
            }
            conventions.insert(name.to_owned(), row);
        }
        let prototype = Regex::new(r"(?m)^([A-Za-z_][\w \*]*?)\n?\b(\w+)\n?\s*\(([^()]*)\);$")
            .expect("a regex");
        let trailing_name = Regex::new(r"\w+$").expect("a regex");
        let mut functions = Vec::new();
        let mut unrunnable = 0;
        for captures in prototype.captures_iter(c) {
            let (result, name, parameters) = (captures[1].trim(), &captures[2], &captures[3]);
            let Some(convention) = conventions.get(name) else {
                continue;
            };
            let address = convention["address"].as_str().expect("checked");
            if parameters.is_empty() || address.contains(OVERLAY_SEPARATOR) {
                continue;
            }
            let declared: Vec<&str> = if parameters == "void" {
                Vec::new()
            } else {
                parameters.split(',').map(str::trim).collect()
            };
            let kinds: Vec<String> = declared
                .iter()
                .map(|parameter| trailing_name.replace(parameter, "").trim().to_owned())
                .collect();
            let sizes: Vec<Option<usize>> = kinds.iter().map(|kind| types.size(kind)).collect();
            let result_size = if result == "void" {
                Some(0)
            } else {
                types.size(result)
            };
            let stack: Vec<(usize, usize)> = convention["stack"]
                .as_array()
                .map(|items| {
                    items
                        .iter()
                        .map(|item| {
                            let field = |name: &str| item[name].as_u64().unwrap_or(0) as usize;
                            (field("offset"), field("size"))
                        })
                        .collect()
                })
                .unwrap_or_default();
            let stack_sizes: Vec<Option<usize>> =
                stack.iter().map(|&(_, size)| Some(size)).collect();
            let layable = !kinds.iter().any(|kind| kind == "...")
                && sizes.iter().all(Option::is_some)
                && result_size.is_some()
                && sizes
                    .iter()
                    .chain([&result_size])
                    .all(|size| size.is_some_and(|size| size <= WIDEST))
                && stack_sizes == sizes;
            if !layable {
                unrunnable += 1;
                continue;
            }
            let Ok(address) = u32::from_str_radix(address, 16) else {
                unrunnable += 1;
                continue;
            };
            functions.push(Function {
                name: name.to_owned(),
                address,
                kinds,
                offsets: stack.iter().map(|&(offset, _)| offset).collect(),
                preserves: preserved(convention),
            });
        }
        Ok(Self {
            functions,
            unrunnable,
            types,
        })
    }

    /// The case'th argument of `kind` at `position`, as its bytes
    /// (`harness.py`'s `argument`, plain cases): a stub for a routine,
    /// a buffer for another pointer.
    fn argument(
        &self,
        firmware: &mut Firmware,
        kind: &str,
        case: usize,
        position: usize,
    ) -> Vec<u8> {
        let real = REALS[case % CASES];
        if self.types.is_routine(kind) {
            return Firmware::stub(position).to_be_bytes().to_vec();
        }
        if self.types.is_pointer(kind) {
            let pointee = kind.trim_end_matches('*').trim();
            let contents: Vec<u8> = match pointee {
                "double" => real.to_be_bytes().repeat(4),
                "float" => (real as f32).to_be_bytes().repeat(8),
                "char" => TEXT.to_vec(),
                _ => (0..crate::firmware::BUFFER_SPACING as usize)
                    .map(|index| (case * 37 + index * 11) as u8)
                    .collect(),
            };
            return firmware.buffer(&contents).to_be_bytes().to_vec();
        }
        match kind {
            "double" => return real.to_be_bytes().to_vec(),
            "float" => return (real as f32).to_be_bytes().to_vec(),
            _ => {}
        }
        match self.types.size(kind) {
            Some(1) => CHARS[case % CASES].to_be_bytes().to_vec(),
            Some(2) => SHORTS[case % CASES].to_be_bytes().to_vec(),
            Some(8) => INTEGERS[case % CASES].to_be_bytes().to_vec(),
            _ => (INTEGERS[case % CASES] as u32).to_be_bytes().to_vec(),
        }
    }

    /// Calls `function` on its `case`'th arguments, from fresh memory.
    pub fn call(
        &self,
        firmware: &mut Firmware,
        caller_name: u32,
        function: &Function,
        case: usize,
    ) -> Outcome {
        let laid_out = self.lay_out(firmware, caller_name, function, case);
        run(firmware, function, laid_out, None).1
    }

    /// Lays out `function`'s call on its `case`'th arguments in fresh
    /// memory.
    fn lay_out(
        &self,
        firmware: &mut Firmware,
        caller_name: u32,
        function: &Function,
        case: usize,
    ) -> LaidOut {
        firmware.fresh();
        let values: Vec<Vec<u8>> = function
            .kinds
            .iter()
            .enumerate()
            .map(|(position, kind)| self.argument(firmware, kind, case + position, position))
            .collect();
        let system_byte = if MASK_SETTERS.contains(&function.name.as_str()) {
            let mask = u16::from_be_bytes([values[0][0], values[0][1]]);
            SUPERVISOR & !status::INTERRUPT_MASK | mask & status::INTERRUPT_MASK
        } else {
            SUPERVISOR
        } & SYSTEM_BYTE;
        let arguments = original_layout(&function.offsets, &values);
        let sp = firmware.push_call(STACK_TOP, &arguments);
        let frame: Vec<u8> = [0, RETURN, caller_name]
            .iter()
            .flat_map(|long| long.to_be_bytes())
            .collect();
        firmware.write(STACK_TOP, &frame);
        LaidOut { sp, system_byte }
    }
}

/// A call laid out in memory.
#[derive(Debug, Clone, Copy)]
struct LaidOut {
    /// The stack pointer it starts with.
    sp: u32,
    /// SR's system byte it should return with.
    system_byte: u16,
}

/// Runs a call `Corpus::lay_out` laid out, telling `observe` each
/// instruction: its end and its outcome.
fn run(
    firmware: &mut Firmware,
    function: &Function,
    laid_out: LaidOut,
    observe: Option<&mut dyn FnMut(Executed)>,
) -> (Call, Outcome) {
    let starting = starting_registers();
    let call = firmware.call_observed(
        function.address,
        laid_out.sp,
        |registers| {
            for (index, &value) in starting.iter().enumerate() {
                if index < registers.data.len() {
                    registers.data[index] = value;
                } else {
                    registers.set_address(index - registers.data.len(), value);
                }
            }
        },
        observe,
    );
    let outcome = outcome(
        &call,
        laid_out.sp,
        &starting,
        &function.preserves,
        laid_out.system_byte,
    );
    (call, outcome)
}

/// What watches each case of a function: memory as it starts, each
/// instruction it runs, and its end.
pub trait CaseObserver {
    /// Memory as the case starts, before the core runs it.
    fn before(&mut self, firmware: &Firmware);
    /// An instruction the core ran.
    fn executed(&mut self, executed: Executed);
    /// The case's end on the core, its outcome, and memory then.
    fn after(&mut self, firmware: &Firmware, call: &Call, outcome: &Outcome);
}

/// Each register's value at a call's start, in `REGISTERS`' order:
/// a sentinel each, but A6, the caller's frame.
fn starting_registers() -> [u32; 15] {
    std::array::from_fn(|index| {
        if index == A6 {
            STACK_TOP
        } else {
            SENTINEL + index as u32
        }
    })
}

/// Arguments where the original reads them, above the return address,
/// `UNDECLARED` between and after them (`function_check.py`'s
/// `original_layout`).
fn original_layout(offsets: &[usize], values: &[Vec<u8>]) -> Vec<u8> {
    let end = offsets
        .iter()
        .zip(values)
        .map(|(offset, value)| offset + value.len())
        .max()
        .unwrap_or(FIRST_ARGUMENT);
    let end = end + (end - FIRST_ARGUMENT) % STACK_ALIGNMENT;
    let mut layout: Vec<u8> = UNDECLARED
        .iter()
        .cycle()
        .take(end - FIRST_ARGUMENT)
        .copied()
        .collect();
    for (offset, value) in offsets.iter().zip(values) {
        let at = offset - FIRST_ARGUMENT;
        layout[at..at + value.len()].copy_from_slice(value);
    }
    layout.extend_from_slice(UNDECLARED);
    layout
}

/// What one call came to.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Outcome {
    /// It returned as its convention says.
    Returned,
    /// It stopped where smartclock's harness stops a call: a trap it
    /// models or that never returns, or a spin.
    Ended(Stopped),
    /// It returned, breaking its convention: how.
    Broke(Vec<String>),
    /// The core does not implement an opcode it reached.
    Unimplemented(u16),
    /// It went where smartclock's harness skips a call: beyond the
    /// memory and peripherals it maps, into data, not code, or to an odd
    /// address, where the 68020 faults as well.
    Skipped(Stopped),
    /// It read or wrote a word or long at an odd address, an address
    /// error on the CPU32 (CPU32RM 6.2.3), which smartclock's 68020
    /// makes as a misaligned access: a generated argument's doing.
    Misaligned(Stopped),
    /// It took an exception smartclock's harness would not, at the
    /// instruction at the address.
    Exception(Exception, u32),
    /// It ran `STEP_LIMIT` instructions, or halted.
    Stuck(Stopped),
}

/// How a call that ended so came out, which should leave SR's system
/// byte `system_byte`.
fn outcome(
    call: &Call,
    sp: u32,
    starting: &[u32; 15],
    preserves: &[usize],
    system_byte: u16,
) -> Outcome {
    match call.stopped {
        Stopped::Returned => {
            let registers = &call.registers;
            let value = |index: usize| {
                if index < registers.data.len() {
                    registers.data[index]
                } else {
                    registers.address(index - registers.data.len())
                }
            };
            let mut broken: Vec<String> = preserves
                .iter()
                .filter(|&&index| value(index) != starting[index])
                .map(|&index| {
                    format!(
                        "{} {:#x}, was {:#x}",
                        REGISTERS[index],
                        value(index),
                        starting[index]
                    )
                })
                .collect();
            if registers.ssp != sp + 4 {
                broken.push(format!("SP {:#x}, wanted {:#x}", registers.ssp, sp + 4));
            }
            if registers.sr() & SYSTEM_BYTE != system_byte {
                broken.push(format!("SR {:#06x}", registers.sr()));
            }
            if broken.is_empty() {
                Outcome::Returned
            } else {
                Outcome::Broke(broken)
            }
        }
        Stopped::Trap(_) | Stopped::Spin => Outcome::Ended(call.stopped),
        Stopped::Unimplemented { pc, .. } if !in_rom(pc) => Outcome::Skipped(call.stopped),
        Stopped::Unimplemented { opcode, .. } => Outcome::Unimplemented(opcode),
        Stopped::Exception { exception, pc } => match exception {
            // smartclock's harness ends a call at a zero divide, and at a
            // write to code, which on the board is a bus error: the boot
            // chip select is read only (its `harness.py`, `BUS_ERROR`).
            _ if exception.vector() == Vector::ZERO_DIVIDE => Outcome::Ended(call.stopped),
            Exception::Fault(fault)
                if fault.vector == Vector::BUS_ERROR
                    && fault.cycle == CycleKind::Write
                    && in_rom(fault.address.0) =>
            {
                Outcome::Ended(call.stopped)
            }
            Exception::Fault(fault)
                if !maps(fault.address.0)
                    || fault.vector == Vector::ADDRESS_ERROR && fault.cycle == CycleKind::Fetch =>
            {
                Outcome::Skipped(call.stopped)
            }
            Exception::Fault(fault) if fault.vector == Vector::ADDRESS_ERROR => {
                Outcome::Misaligned(call.stopped)
            }
            _ => Outcome::Exception(exception, pc),
        },
        Stopped::Halted | Stopped::StepLimit => Outcome::Stuck(call.stopped),
    }
}

/// Whether `address` is in the image's ROM, on the 24 address lines.
const fn in_rom(address: u32) -> bool {
    let at = address & ((1 << ADDRESS_BITS) - 1);
    at.wrapping_sub(ROM) < ROM_BYTES
}

/// Why `function` taking an exception through `vector` is the CPU32's
/// answer to its arguments (`EXPLAINED`), if it is.
#[must_use]
pub fn explanation(function: &str, vector: Vector) -> Option<&'static str> {
    EXPLAINED
        .iter()
        .find(|&&(name, explained, _)| name == function && explained == vector)
        .map(|&(_, _, why)| why)
}

/// A function's verdict over its cases: the first case that failed
/// decides it; else the first skipped or explained; else it passed.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Verdict {
    /// Every case returned or ended as smartclock's would.
    Passed,
    /// A case went where smartclock's harness skips it, the others
    /// passing.
    Skipped(Stopped),
    /// A case made a misaligned access, the others passing.
    Misaligned(Stopped),
    /// A case took an exception `EXPLAINED` explains, the others
    /// passing: the vector and why.
    Explained(Vector, &'static str),
    /// A case broke its convention.
    Broke(Vec<String>),
    /// A case reached an opcode the core does not implement.
    Unimplemented(u16),
    /// A case took an exception at the instruction at the address.
    Exception(Exception, u32),
    /// A case got stuck.
    Stuck(Stopped),
}

/// Runs every case of `function`.
pub fn verdict(
    corpus: &Corpus,
    firmware: &mut Firmware,
    caller_name: u32,
    function: &Function,
) -> Verdict {
    observed_verdict(corpus, firmware, caller_name, function, None)
}

/// `verdict`, with `observer` watching every case: all of them, not
/// only those up to the one that decides.
pub fn observed_verdict(
    corpus: &Corpus,
    firmware: &mut Firmware,
    caller_name: u32,
    function: &Function,
    mut observer: Option<&mut dyn CaseObserver>,
) -> Verdict {
    let mut passing = Verdict::Passed;
    let mut decided = None;
    for case in 0..CASES {
        if decided.is_some() && observer.is_none() {
            break;
        }
        let laid_out = corpus.lay_out(firmware, caller_name, function, case);
        let outcome = match observer.as_deref_mut() {
            Some(observer) => {
                observer.before(firmware);
                let (call, outcome) = run(
                    firmware,
                    function,
                    laid_out,
                    Some(&mut |executed| observer.executed(executed)),
                );
                observer.after(firmware, &call, &outcome);
                outcome
            }
            None => run(firmware, function, laid_out, None).1,
        };
        if decided.is_some() {
            continue;
        }
        let not_passed = match outcome {
            Outcome::Returned | Outcome::Ended(_) => continue,
            Outcome::Skipped(stopped) => Verdict::Skipped(stopped),
            Outcome::Misaligned(stopped) => Verdict::Misaligned(stopped),
            Outcome::Exception(exception, pc) => {
                match explanation(&function.name, exception.vector()) {
                    Some(why) => Verdict::Explained(exception.vector(), why),
                    None => {
                        decided = Some(Verdict::Exception(exception, pc));
                        continue;
                    }
                }
            }
            Outcome::Broke(how) => Verdict::Broke(how),
            Outcome::Unimplemented(opcode) => Verdict::Unimplemented(opcode),
            Outcome::Stuck(stopped) => Verdict::Stuck(stopped),
        };
        match not_passed {
            Verdict::Broke(_) | Verdict::Unimplemented(_) | Verdict::Stuck(_) => {
                decided = Some(not_passed);
            }
            _ if passing == Verdict::Passed => passing = not_passed,
            _ => {}
        }
    }
    decided.unwrap_or(passing)
}

#[cfg(test)]
mod tests {
    use cpu32_oracle::state::State;
    use mc683xx_cpu32::address::Address;
    use mc683xx_cpu32::exception::CycleKind;
    use mc683xx_cpu32::exception::Exception;
    use mc683xx_cpu32::exception::Fault;
    use mc683xx_cpu32::exception::Vector;
    use mc683xx_cpu32::function_code::FunctionCode;
    use mc683xx_cpu32::registers::Registers;
    use mc683xx_cpu32::size::Size;

    use super::Corpus;
    use super::Outcome;
    use super::Verdict;
    use super::original_layout;
    use super::outcome;
    use super::preserved;
    use super::starting_registers;
    use super::verdict;
    use crate::firmware::Call;
    use crate::firmware::Firmware;
    use crate::firmware::ROM_BYTES;
    use crate::firmware::SUPERVISOR;
    use crate::firmware::Stopped;

    /// A returned call's registers as a call starts them, SP past the
    /// return address at `sp`.
    fn returned(sp: u32) -> Call {
        let mut registers = Registers::default();
        registers.set_sr(SUPERVISOR);
        let starting = starting_registers();
        registers.data.copy_from_slice(&starting[..8]);
        for (number, &value) in starting[8..].iter().enumerate() {
            registers.set_address(number, value);
        }
        registers.ssp = sp + 4;
        Call {
            stopped: Stopped::Returned,
            started: State::default(),
            registers,
            steps: 1,
        }
    }

    /// A call that ended at a fault of `vector` in a `cycle` at
    /// `address`.
    fn faulted(vector: Vector, cycle: CycleKind, address: u32) -> Call {
        Call {
            stopped: Stopped::Exception {
                exception: Exception::Fault(Fault {
                    vector,
                    address: Address(address),
                    function_code: FunctionCode::SUPERVISOR_DATA,
                    size: Size::Word,
                    long: false,
                    cycle,
                    data: 0,
                    read_modify_write: false,
                }),
                pc: 0x400,
            },
            ..returned(0)
        }
    }

    #[test]
    fn exceptions_smartclock_ends_or_skips_at_are_not_failures() {
        let classify = |call: &Call| outcome(call, 0, &starting_registers(), &[], SUPERVISOR);
        let zero_divide = Call {
            stopped: Stopped::Exception {
                exception: Exception::Long {
                    vector: Vector::ZERO_DIVIDE,
                    pc: Address(0x402),
                    address: Address(0x400),
                },
                pc: 0x400,
            },
            ..returned(0)
        };
        assert!(matches!(classify(&zero_divide), Outcome::Ended(_)));
        let write_to_rom = faulted(Vector::BUS_ERROR, CycleKind::Write, 0x30);
        assert!(matches!(classify(&write_to_rom), Outcome::Ended(_)));
        let beyond = faulted(Vector::BUS_ERROR, CycleKind::Read, 0x11_0000);
        assert!(matches!(classify(&beyond), Outcome::Skipped(_)));
        let odd_jump = faulted(Vector::ADDRESS_ERROR, CycleKind::Fetch, 0x401);
        assert!(matches!(classify(&odd_jump), Outcome::Skipped(_)));
        let odd_read = faulted(Vector::ADDRESS_ERROR, CycleKind::Read, 0x401);
        assert!(matches!(classify(&odd_read), Outcome::Misaligned(_)));
        // A bus error inside the map is the core's or the runner's.
        let read_of_rom = faulted(Vector::BUS_ERROR, CycleKind::Read, 0x400);
        assert!(matches!(
            classify(&read_of_rom),
            Outcome::Exception(_, 0x400)
        ));
    }

    #[test]
    fn an_io_function_returns_in_d7() {
        let row = serde_json::json!({"name": "duartb_reconfigure", "convention": "unknown"});
        assert!(!preserved(&row).contains(&super::D7));
        let row = serde_json::json!({"name": "f", "convention": "unknown"});
        assert!(preserved(&row).contains(&super::D7));
    }

    #[test]
    fn a_return_keeps_the_convention_or_breaks_it() {
        let sp = 0x70_0000;
        let keeps = preserved(&serde_json::json!({"convention": "unknown"}));
        let starting = starting_registers();
        assert_eq!(
            outcome(&returned(sp), sp, &starting, &keeps, SUPERVISOR),
            Outcome::Returned
        );
        let mut call = returned(sp);
        call.registers.data[2] = 0;
        call.registers.ssp = sp;
        call.registers.set_sr(0);
        let Outcome::Broke(how) = outcome(&call, sp, &starting, &keeps, SUPERVISOR) else {
            panic!("a broken convention passed");
        };
        assert_eq!(
            how,
            [
                "D2 0x0, was 0x5a5a0002",
                "SP 0x700000, wanted 0x700004",
                "SR 0x0000"
            ]
        );
        // D0 and D1 are the callee's to change.
        call = returned(sp);
        call.registers.data[0] = 0;
        assert_eq!(
            outcome(&call, sp, &starting, &keeps, SUPERVISOR),
            Outcome::Returned
        );
    }

    #[test]
    fn layout_puts_arguments_at_their_offsets() {
        let layout = original_layout(&[4, 11], &[vec![1, 2, 3, 4], vec![9]]);
        assert_eq!(&layout[..8], &[1, 2, 3, 4, b'1', b'0', b'1', 9]);
        assert_eq!(&layout[8..], b"101010101010");
    }

    /// A C file and sidecar of one function, `f(int)`, at $400.
    const C: &str = "int f(int param_1);\nvoid g(struct s param_1);\n";
    const SIDECAR: &str = concat!(
        r#"{"address":"00000400","name":"f","convention":"unknown","stack":[{"offset":4,"size":4}]}"#,
        "\n",
        r#"{"address":"00000500","name":"g","convention":"unknown","stack":[{"offset":4,"size":12}]}"#,
        "\n"
    );

    #[test]
    fn finds_the_functions_it_can_call() {
        let corpus = Corpus::new(C, SIDECAR).unwrap();
        assert_eq!(corpus.functions.len(), 1);
        assert_eq!(corpus.functions[0].name, "f");
        assert_eq!(corpus.functions[0].address, 0x400);
        assert_eq!(corpus.unrunnable, 1);
    }

    #[test]
    fn a_function_that_keeps_its_convention_passes() {
        // MOVE.L (4, SP), D0; RTS
        let mut image = vec![0; ROM_BYTES as usize];
        image[0x400..0x406].copy_from_slice(&[0x20, 0x2f, 0x00, 0x04, 0x4e, 0x75]);
        let corpus = Corpus::new(C, SIDECAR).unwrap();
        let mut firmware = Firmware::new(&image).unwrap();
        assert_eq!(
            verdict(&corpus, &mut firmware, 0, &corpus.functions[0]),
            Verdict::Passed
        );
        // MOVEQ #0, D2; RTS: D2 is the caller's.
        image[0x400..0x404].copy_from_slice(&[0x74, 0x00, 0x4e, 0x75]);
        let mut firmware = Firmware::new(&image).unwrap();
        assert!(matches!(
            verdict(&corpus, &mut firmware, 0, &corpus.functions[0]),
            Verdict::Broke(_)
        ));
    }

    #[test]
    fn a_mask_setter_leaves_the_mask_it_was_given() {
        const C: &str = "uint16_t set_interrupt_mask(uint16_t sr);\n";
        const SIDECAR: &str = r#"{"address":"00000400","name":"set_interrupt_mask","convention":"unknown","stack":[{"offset":4,"size":2}]}"#;
        // A hand-written mask setter, not the firmware's: MOVE.W (4, SP),
        // D1; ANDI.W #$0700, D1; ORI.W #$2000, D1; MOVE.W D1, SR; RTS
        let code: [u16; 9] = [
            0x322f, 0x0004, 0x0241, 0x0700, 0x0041, 0x2000, 0x46c1, 0x4e75, 0,
        ];
        let mut image = vec![0; ROM_BYTES as usize];
        for (index, word) in code.iter().enumerate() {
            let at = 0x400 + 2 * index;
            image[at..at + 2].copy_from_slice(&word.to_be_bytes());
        }
        let corpus = Corpus::new(C, SIDECAR).unwrap();
        let mut firmware = Firmware::new(&image).unwrap();
        assert_eq!(
            verdict(&corpus, &mut firmware, 0, &corpus.functions[0]),
            Verdict::Passed
        );
        // ORI.W #$2700, D1: the mask kept, not the argument's.
        image[0x40a..0x40c].copy_from_slice(&0x2700u16.to_be_bytes());
        let mut firmware = Firmware::new(&image).unwrap();
        assert!(matches!(
            verdict(&corpus, &mut firmware, 0, &corpus.functions[0]),
            Verdict::Broke(_)
        ));
    }
}
