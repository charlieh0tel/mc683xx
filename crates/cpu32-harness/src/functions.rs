//! The firmware function corpus: every C function of an image the
//! harness can lay out a call to, called on generated arguments, as
//! smartclock's (github.com/charlieh0tel/smartclock)
//! `tools/firmware/function_check.py` and `harness.py` call the image's
//! copy (by this project's author, ported).  The arguments come from the
//! decompiled C's prototypes and the `.conventions.jsonl` sidecar's
//! stack offsets.
//!
//! smartclock's check compares the image's copy against gcc's; here
//! there is no second copy, so a call passes when it returns as its
//! convention says (SP past the return address, the registers it keeps
//! kept, SR's system byte as it was, but `MASK_SETTERS`' mask) or stops
//! where smartclock's would (a trap the harness models or that never
//! returns, a spin, a zero divide, a write to ROM).  One that goes where
//! smartclock's would skip it, makes a misaligned access or takes an
//! exception `EXPLAINED` explains is counted apart.  Results are
//! compared against oracles in `oracles`.  Of `function_check.py`'s
//! set-up, only the plain cases are here: no kernel tables or initializers in RAM, the peripherals
//! as smartclock's first peripheral case has them, no pointer cases, no
//! task (user state) cases, no installer overlay.

